-- Check table sizes and transaction totals
SELECT
    (SELECT COUNT(*) FROM FINTRUST_RECOVERY_LAB.BANKING.BRANCHES) AS BRANCHES,
    (SELECT COUNT(*) FROM FINTRUST_RECOVERY_LAB.BANKING.CUSTOMERS) AS CUSTOMERS,
    (SELECT COUNT(*) FROM FINTRUST_RECOVERY_LAB.BANKING.ACCOUNTS) AS ACCOUNTS,
    COUNT(*) AS TRANSACTIONS,
    COUNT(DISTINCT TRANSACTION_ID) AS UNIQUE_TRANSACTION_IDS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'DEPOSIT' THEN AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'WITHDRAWAL' THEN AMOUNT ELSE 0 END) AS TOTAL_WITHDRAWALS
FROM FINTRUST_RECOVERY_LAB.BANKING.TRANSACTIONS;

-- Step 14: Compare recovered totals with the clone
SELECT
    'Recovered table' AS DATA_SOURCE,
    COUNT(*) AS TRANSACTION_COUNT,
    COUNT(DISTINCT TRANSACTION_ID) AS UNIQUE_TRANSACTION_IDS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'DEPOSIT'
        THEN AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'WITHDRAWAL'
        THEN AMOUNT ELSE 0 END) AS TOTAL_WITHDRAWALS
FROM FINTRUST_RECOVERY_LAB.BANKING.TRANSACTIONS

UNION ALL

SELECT
    'Baseline clone' AS DATA_SOURCE,
    COUNT(*) AS TRANSACTION_COUNT,
    COUNT(DISTINCT TRANSACTION_ID) AS UNIQUE_TRANSACTION_IDS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'DEPOSIT'
        THEN AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'WITHDRAWAL'
        THEN AMOUNT ELSE 0 END) AS TOTAL_WITHDRAWALS
FROM FINTRUST_RECOVERY_LAB.BANKING.TRANSACTIONS_BEFORE_DELETE;

-- Step 15: Check differences per account
WITH combined AS (
    SELECT
        ACCOUNT_ID,
        'Recovered' AS SOURCE,
        TRANSACTION_TYPE,
        AMOUNT
    FROM FINTRUST_RECOVERY_LAB.BANKING.TRANSACTIONS

    UNION ALL

    SELECT
        ACCOUNT_ID,
        'Baseline' AS SOURCE,
        TRANSACTION_TYPE,
        AMOUNT
    FROM FINTRUST_RECOVERY_LAB.BANKING.TRANSACTIONS_BEFORE_DELETE
)
SELECT
    ACCOUNT_ID,
    SUM(CASE WHEN SOURCE = 'Recovered' THEN 1 ELSE 0 END)
        - SUM(CASE WHEN SOURCE = 'Baseline' THEN 1 ELSE 0 END)
        AS ROW_COUNT_DIFFERENCE,

    SUM(CASE WHEN SOURCE = 'Recovered'
              AND TRANSACTION_TYPE = 'DEPOSIT'
             THEN AMOUNT ELSE 0 END)
        - SUM(CASE WHEN SOURCE = 'Baseline'
                    AND TRANSACTION_TYPE = 'DEPOSIT'
                   THEN AMOUNT ELSE 0 END)
        AS DEPOSIT_DIFFERENCE,

    SUM(CASE WHEN SOURCE = 'Recovered'
              AND TRANSACTION_TYPE = 'WITHDRAWAL'
             THEN AMOUNT ELSE 0 END)
        - SUM(CASE WHEN SOURCE = 'Baseline'
                    AND TRANSACTION_TYPE = 'WITHDRAWAL'
                   THEN AMOUNT ELSE 0 END)
        AS WITHDRAWAL_DIFFERENCE
FROM combined
GROUP BY ACCOUNT_ID
ORDER BY ACCOUNT_ID;

