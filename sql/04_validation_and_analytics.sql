-- Step 23: Summarize by account type
SELECT
    a.ACCOUNT_TYPE,
    a.CURRENCY_CODE,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'DEPOSIT'
        THEN t.AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'WITHDRAWAL'
        THEN t.AMOUNT ELSE 0 END) AS TOTAL_WITHDRAWALS
FROM FINTRUST_RECOVERY_LAB.BANKING.TRANSACTIONS AS t
JOIN FINTRUST_RECOVERY_LAB.BANKING.ACCOUNTS AS a
    ON t.ACCOUNT_ID = a.ACCOUNT_ID
GROUP BY a.ACCOUNT_TYPE, a.CURRENCY_CODE
ORDER BY a.ACCOUNT_TYPE, a.CURRENCY_CODE;

-- Step 24: Summarize by branch location
SELECT
    b.CITY,
    b.REGION,
    a.CURRENCY_CODE,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'DEPOSIT'
        THEN t.AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN t.TRANSACTION_TYPE = 'WITHDRAWAL'
        THEN t.AMOUNT ELSE 0 END) AS TOTAL_WITHDRAWALS
FROM FINTRUST_RECOVERY_LAB.BANKING.TRANSACTIONS AS t
JOIN FINTRUST_RECOVERY_LAB.BANKING.ACCOUNTS AS a
    ON t.ACCOUNT_ID = a.ACCOUNT_ID
JOIN FINTRUST_RECOVERY_LAB.BANKING.BRANCHES AS b
    ON a.BRANCH_ID = b.BRANCH_ID
GROUP BY b.CITY, b.REGION, a.CURRENCY_CODE
ORDER BY b.CITY;

-- Step 25: Summarize by month
SELECT
    TO_CHAR(TRANSACTION_TIMESTAMP, 'YYYY-MM') AS TRANSACTION_MONTH,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(CASE WHEN TRANSACTION_TYPE = 'DEPOSIT'
        THEN AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'WITHDRAWAL'
        THEN AMOUNT ELSE 0 END) AS TOTAL_WITHDRAWALS,
    SUM(CASE
        WHEN TRANSACTION_TYPE = 'DEPOSIT' THEN AMOUNT
        WHEN TRANSACTION_TYPE = 'WITHDRAWAL' THEN -AMOUNT
        ELSE 0
    END) AS NET_MOVEMENT
FROM FINTRUST_RECOVERY_LAB.BANKING.TRANSACTIONS
GROUP BY TRANSACTION_MONTH
ORDER BY TRANSACTION_MONTH;

